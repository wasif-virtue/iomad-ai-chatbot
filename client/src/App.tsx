
import { useState, type FormEvent } from "react";
import "./App.css";

type Message = {
  role: "user" | "assistant";
  content: string;
};

function App() {
  const [messages, setMessages] = useState<Message[]>([]);
  const [question, setQuestion] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  async function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();

    const trimmedQuestion = question.trim();

    if (!trimmedQuestion || loading) return;

    setMessages((previous) => [
      ...previous,
      { role: "user", content: trimmedQuestion },
    ]);
    setQuestion("");
    setError("");
    setLoading(true);

    try {
      const response = await fetch("/api/chat", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({ question: trimmedQuestion }),
      });

      const data: { answer?: string; error?: string } =
        await response.json();

      if (!response.ok) {
        throw new Error(data.error || "The request failed.");
      }

      if (typeof data.answer !== "string") {
        throw new Error("The server returned an invalid response.");
      }

      setMessages((previous) => [
        ...previous,
        { role: "assistant", content: data.answer! },
      ]);
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : "Could not connect to the chatbot."
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <main className="app">
      <header className="header">
        <div className="brand-icon">AI</div>
        <div>
          <h1>Knowledge Assistant</h1>
          <p>Local AI chatbot prototype</p>
        </div>
        <span className="status">
          <span className="status-dot" />
          Local prototype
        </span>
      </header>

      <section className="chat">
        {messages.length === 0 ? (
          <div className="welcome">
            <div className="welcome-icon">✦</div>
            <h2>How can I help you?</h2>
            <p>
              Ask a question to test your local AI assistant.
            </p>
            <button
              className="suggestion"
              type="button"
              onClick={() =>
                setQuestion("What is Moodle and how does it work?")
              }
            >
              What is Moodle and how does it work?
              <span>↗</span>
            </button>
          </div>
        ) : (
          <div className="messages" aria-live="polite">
            {messages.map((message, index) => (
              <article
                className={`message ${message.role}`}
                key={`${index}-${message.role}`}
              >
                <div className="message-label">
                  {message.role === "user" ? "You" : "Assistant"}
                </div>
                <div className="message-content">
                  {message.content}
                </div>
              </article>
            ))}
            {loading && (
              <div className="loading" role="status">
                Assistant is thinking...
              </div>
            )}
          </div>
        )}

        {error && <p className="error" role="alert">{error}</p>}
      </section>

      <form className="composer" onSubmit={handleSubmit}>
        <label className="sr-only" htmlFor="question">
          Your question
        </label>
        <textarea
          id="question"
          value={question}
          onChange={(event) => setQuestion(event.target.value)}
          placeholder="Ask your question..."
          rows={2}
          maxLength={2000}
          disabled={loading}
          onKeyDown={(event) => {
            if (
              event.key === "Enter" &&
              !event.shiftKey &&
              !event.nativeEvent.isComposing
            ) {
              event.preventDefault();
              event.currentTarget.form?.requestSubmit();
            }
          }}
        />
        <div className="composer-footer">
          <span>Enter to send · Shift+Enter for a new line</span>
          <button
            type="submit"
            disabled={loading || !question.trim()}
          >
            {loading ? "Thinking..." : "Send ↑"}
          </button>
        </div>
      </form>

      <footer className="footer">
        Prototype only · Answers are generated by a local AI model
      </footer>
    </main>
  );
}

export default App;
